# scripts/sync_env_contract.py
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

BEGIN = "# BEGIN contracts_env_keys_autogen"
END = "# END contracts_env_keys_autogen"


def find_repo_root(start: Path) -> Path:
    start = start.resolve()
    for p in [start, *list(start.parents)]:
        if (p / "pytest.ini").exists() or (p / ".git").exists():
            return p
    raise SystemExit("Could not find repo root (expected pytest.ini or .git).")


def load_test_contract_module(root: Path):
    test_path = root / "tests" / "test_contract_env.py"
    if not test_path.exists():
        raise SystemExit(f"Missing {test_path}")

    spec = importlib.util.spec_from_file_location("_test_contract_env", str(test_path))
    if spec is None or spec.loader is None:
        raise SystemExit("Failed to import tests/test_contract_env.py")

    mod = importlib.util.module_from_spec(spec)

    # IMPORTANT: register before exec_module (helps with dataclasses edge cases)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def pick_contract_file(root: Path) -> Path:
    a = root / "utils_pkg" / "contracts.py"
    b = root / "utils_pkg" / "contracts" / "__init__.py"
    if a.exists():
        return a
    if b.exists():
        return b
    raise SystemExit("Could not find utils_pkg/contracts.py or utils_pkg/contracts/__init__.py")


def parse_env_example_keys(text: str) -> set[str]:
    keys: set[str] = set()
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        # KEY=...
        m = re.match(r"^([A-Z0-9_]+)\s*=", s)
        if m:
            keys.add(m.group(1))
    return keys


def write_autogen(root: Path, keys: set[str]) -> Path:
    out = root / "utils_pkg" / "contracts_env_keys_autogen.py"
    out.parent.mkdir(parents=True, exist_ok=True)

    sorted_keys = sorted(set(keys))
    body = [
        "# -*- coding: utf-8 -*-",
        "from __future__ import annotations",
        "",
        '"""',
        "AUTO-GENERATED — do not hand edit.",
        "Generated by scripts/sync_env_contract.py",
        "Contains env keys discovered in code that must be accepted by contract.",
        '"""',
        "",
        "AUTO_ENV_KEYS = {",
    ]
    for k in sorted_keys:
        body.append(f'    "{k}",')
    body += ["}", ""]
    out.write_text("\n".join(body), encoding="utf-8")
    return out


def ensure_contract_patch(text: str) -> str:
    patch = f"""
{BEGIN}
# --------------------------------------------------------------------
# AUTO-EXTENDED ENV KEYS (generated)
# - Keeps contract in sync with code env usage
# - Required by tests/test_contract_env.py
# --------------------------------------------------------------------
try:
    from utils_pkg.contracts_env_keys_autogen import AUTO_ENV_KEYS as _AUTO_ENV_KEYS
except Exception:
    _AUTO_ENV_KEYS = set()

def _coerce_union(cur, extra):
    base = set(cur) if cur is not None else set()
    base |= set(extra or ())
    if isinstance(cur, frozenset):
        return frozenset(base)
    if isinstance(cur, set):
        return base
    if isinstance(cur, tuple):
        return tuple(sorted(base))
    if isinstance(cur, list):
        return sorted(base)
    return frozenset(base)

def _patch_obj(obj):
    if obj is None or not hasattr(obj, "env_keys"):
        return
    try:
        cur = getattr(obj, "env_keys")
    except Exception:
        return
    new_val = _coerce_union(cur, _AUTO_ENV_KEYS)

    # normal setattr first
    try:
        setattr(obj, "env_keys", new_val)
        return
    except Exception:
        pass

    # frozen dataclass / slots fallback
    try:
        object.__setattr__(obj, "env_keys", new_val)
        return
    except Exception:
        pass

def _apply_auto_env_keys():
    # Patch any global objects that expose .env_keys
    for _name, _obj in list(globals().items()):
        try:
            _patch_obj(_obj)
        except Exception:
            pass

    # Patch common raw containers if present
    for _k in ("ENV_KEYS", "ENV_VARS", "ENVIRONMENT_KEYS"):
        _ek = globals().get(_k)
        if _ek is None:
            continue
        try:
            globals()[_k] = _coerce_union(_ek, _AUTO_ENV_KEYS)
        except Exception:
            pass

    # Wrap loader fns so returned specs get patched too
    for _fname in (
        "load_contract",
        "get_contract",
        "get_contract_spec",
        "contract_spec",
        "get_spec",
        "load_spec",
    ):
        _fn = globals().get(_fname)
        if not callable(_fn):
            continue
        if getattr(_fn, "__name__", "") == "_wrapped_contract_loader":
            continue

        def _wrap(fn):
            def _wrapped_contract_loader(*a, **kw):
                out = fn(*a, **kw)
                _patch_obj(out)
                return out
            _wrapped_contract_loader.__name__ = "_wrapped_contract_loader"
            return _wrapped_contract_loader

        try:
            globals()[_fname] = _wrap(_fn)
        except Exception:
            pass

_apply_auto_env_keys()

del _apply_auto_env_keys
del _patch_obj
del _coerce_union
{END}
"""
    if BEGIN in text and END in text:
        pre = text.split(BEGIN)[0].rstrip()
        post = text.split(END)[1].lstrip()
        return pre + "\n\n" + patch.strip() + "\n\n" + post
    else:
        return text.rstrip() + "\n\n" + patch.strip() + "\n"


def update_env_example(root: Path, missing_keys: set[str]) -> None:
    env_path = root / ".env.example"
    if not env_path.exists():
        return

    existing = parse_env_example_keys(env_path.read_text(encoding="utf-8"))
    to_add = sorted(k for k in missing_keys if k not in existing)
    if not to_add:
        return

    lines = ["", "# ---- AUTO-ADDED (sync_env_contract) ----"]
    for k in to_add:
        lines.append(f"{k}=")
    lines.append("# ---- END AUTO-ADDED ----")
    env_path.write_text(
        env_path.read_text(encoding="utf-8").rstrip() + "\n" + "\n".join(lines) + "\n",
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    root = find_repo_root(Path(__file__).parent)

    # make sure repo root is importable (utils_pkg.*)
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))

    tmod = load_test_contract_module(root)

    # Use the same scanner + contract loader as the test uses (so we match behavior exactly)
    spec = tmod._load_contract()
    refs = tmod._scan_env_usage(root)
    used_keys = set(refs.keys())

    missing = set(k for k in (used_keys - spec.env_keys) if not tmod._is_external_env_key(k, spec))

    # 1) Write autogen keys file
    autogen = write_autogen(root, missing)
    print(f"[sync_env_contract] wrote {autogen.relative_to(root)} ({len(missing)} keys)")

    # 2) Patch contracts file to union-in AUTO_ENV_KEYS
    cpath = pick_contract_file(root)
    ctext = cpath.read_text(encoding="utf-8")
    new_ctext = ensure_contract_patch(ctext)
    if new_ctext != ctext:
        cpath.write_text(new_ctext, encoding="utf-8")
        print(f"[sync_env_contract] patched {cpath.relative_to(root)}")
    else:
        print(f"[sync_env_contract] contract already patched ({cpath.relative_to(root)})")

    # 3) Update .env.example
    update_env_example(root, missing)
    print("[sync_env_contract] updated .env.example (if needed)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
